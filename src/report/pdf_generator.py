# ── Drawing flowable wrapper ─────────────────────────────────────────────────

class DrawingFlowable(Flowable):
    """Wrap a ReportLab Drawing so it flows naturally in a Platypus story."""

    def __init__(self, drawing: Drawing) -> None:
        Flowable.__init__(self)
        self._drawing = drawing
        self.width  = drawing.width
        self.height = drawing.height

    def draw(self) -> None:
        renderPDF.draw(self._drawing, self.canv, 0, 0)

    def wrap(self, availW: float, availH: float) -> tuple[float, float]:
        return self.width, self.height


# ── Cover page drawing ───────────────────────────────────────────────────────

def _build_cover_drawing(
    product: str,
    period_start: str,
    period_end: str,
    generated_date: str,
    model_name: str,
) -> Drawing:
    """Return a full-page Drawing that forms the cover page."""
    w, h = PAGE_W, PAGE_H
    d = Drawing(w, h)

    # Background fill
    d.add(Rect(0, 0, w, h, fillColor=NAVY, strokeColor=None))

    # Gold accent bar top
    d.add(Rect(0, h - 8 * mm, w, 8 * mm, fillColor=GOLD, strokeColor=None))

    # Lighter panel for meta block (lower third)
    panel_h = 90 * mm
    d.add(Rect(0, 0, w, panel_h,
               fillColor=colors.HexColor("#111F42"), strokeColor=None))
    d.add(Line(0, panel_h, w, panel_h, strokeColor=GOLD, strokeWidth=1.5))

    # Gold accent bar bottom
    d.add(Rect(0, 0, w, 6 * mm, fillColor=GOLD, strokeColor=None))

    # Vertical left accent stripe
    d.add(Rect(MARGIN_LEFT - 5 * mm, panel_h, 3, h - panel_h - 8 * mm,
               fillColor=GOLD, strokeColor=None))

    # --- DISCLAIMER BAND ---
    dband_h = 14 * mm
    d.add(Rect(0, panel_h - dband_h, w, dband_h,
               fillColor=colors.HexColor("#7A1800"), strokeColor=None))
    d.add(String(
        w / 2, panel_h - dband_h + 4,
        "⚠  TECHNICAL EVALUATION EXERCISE — NOT A REAL REGULATORY SUBMISSION  ⚠",
        fontName="Helvetica-Bold",
        fontSize=8,
        fillColor=colors.HexColor("#FFD700"),
        textAnchor="middle",
    ))

    # --- Main title block ---
    tx = MARGIN_LEFT + 2 * mm
    ty = h - 38 * mm

    d.add(String(tx, ty, "PERIODIC ADVERSE DRUG EXPERIENCE REPORT",
                 fontName="Helvetica-Bold", fontSize=10,
                 fillColor=GOLD, textAnchor="start"))
    d.add(String(tx, ty - 16, "PADER-STYLE SAFETY REPORT",
                 fontName="Helvetica", fontSize=8.5,
                 fillColor=colors.HexColor("#8BAAD4"), textAnchor="start"))

    # Product name — large
    d.add(String(tx, ty - 44, product,
                 fontName="Helvetica-Bold", fontSize=36,
                 fillColor=colors.white, textAnchor="start"))

    # Divider
    d.add(Line(tx, ty - 56, w - MARGIN_RIGHT, ty - 56,
               strokeColor=GOLD, strokeWidth=0.8))

    # Report type subtitle
    d.add(String(tx, ty - 70, "Periodic Adverse Drug Experience Report (PADER-style)",
                 fontName="Helvetica", fontSize=12,
                 fillColor=colors.HexColor("#B0C4DE"), textAnchor="start"))

    # --- Meta block (lower panel) ---
    mx = MARGIN_LEFT
    my = panel_h - dband_h - 12 * mm

    meta_items = [
        ("Reporting Period",   f"{period_start}  to  {period_end}"),
        ("Application Number", "Not supplied"),
        ("Report Generated",   generated_date),
        ("Generation Engine",  model_name),
        ("Report Format",      "ICH E2C(R2)-aligned PADER-style"),
    ]
    row_h = 10 * mm
    for i, (label, value) in enumerate(meta_items):
        yy = my - i * row_h
        d.add(String(mx, yy, label + ":",
                     fontName="Helvetica-Bold", fontSize=8,
                     fillColor=GOLD, textAnchor="start"))
        d.add(String(mx + 52 * mm, yy, value,
                     fontName="Helvetica", fontSize=8,
                     fillColor=colors.HexColor("#CBD5E0"), textAnchor="start"))

    # GenAR system identification
    d.add(String(w / 2, 8 * mm + 2,
                 "Generated by GenAR v0 — Evidence-Grounded PADER Report System",
                 fontName="Helvetica", fontSize=7,
                 fillColor=NAVY, textAnchor="middle"))

    return d


# ── Header / Footer callbacks ────────────────────────────────────────────────

def _make_header_footer(product: str, report_period: str):
    def on_page(canvas, doc):
        canvas.saveState()
        page_num = doc.page

        # Skip header/footer on cover (page 1)
        if page_num == 1:
            canvas.restoreState()
            return

        # ── Header ──
        header_y = PAGE_H - MARGIN_TOP + 8 * mm
        # Left: product name
        canvas.setFont("Helvetica-Bold", 7.5)
        canvas.setFillColor(NAVY)
        canvas.drawString(MARGIN_LEFT, header_y, product.upper())
        # Centre: report type
        canvas.setFont("Helvetica", 7)
        canvas.setFillColor(SLATE)
        canvas.drawCentredString(PAGE_W / 2, header_y, "PADER-STYLE SAFETY REPORT")
        # Right: period
        canvas.drawRightString(PAGE_W - MARGIN_RIGHT, header_y, report_period)
        # Rule
        canvas.setStrokeColor(GOLD)
        canvas.setLineWidth(0.8)
        canvas.line(MARGIN_LEFT, header_y - 2.5 * mm,
                    PAGE_W - MARGIN_RIGHT, header_y - 2.5 * mm)

        # ── Footer ──
        footer_y = MARGIN_BOTTOM - 10 * mm
        # Disclaimer
        canvas.setFont("Helvetica-Oblique", 6.5)
        canvas.setFillColor(SLATE)
        canvas.drawCentredString(PAGE_W / 2, footer_y + 4 * mm,
                                 "TECHNICAL EVALUATION EXERCISE — NOT A REGULATORY SUBMISSION")
        # Rule
        canvas.setStrokeColor(MID_GREY)
        canvas.setLineWidth(0.5)
        canvas.line(MARGIN_LEFT, footer_y + 3 * mm,
                    PAGE_W - MARGIN_RIGHT, footer_y + 3 * mm)
        # Page number
        canvas.setFont("Helvetica", 7.5)
        canvas.setFillColor(SLATE)
        canvas.drawCentredString(PAGE_W / 2, footer_y,
                                 f"Page {page_num}")
        canvas.restoreState()

    return on_page


# ── Section helpers ──────────────────────────────────────────────────────────

def _section_heading(number: str, title: str) -> list:
    """Return flowables for a numbered section heading with gold underline."""
    label = f"{number}  {title}" if number else title
    return [
        Spacer(1, 4 * mm),
        Paragraph(label, Styles.h1),
        HRFlowable(width=CONTENT_W, thickness=1.2, color=GOLD, spaceAfter=4),
        Spacer(1, 2 * mm),
    ]


def _sub_heading(title: str) -> list:
    return [Spacer(1, 2 * mm), Paragraph(title, Styles.h2)]


def _ev_tag(ev_ids: list[str]) -> Paragraph:
    ids_text = "  ".join(f"[{i}]" for i in ev_ids)
    return Paragraph(
        f"<font color='#2A4380'><b>Evidence: </b>{ids_text}</font>",
        Styles.body_small,
    )


def _warn_box(text: str) -> Table:
    """An amber warning / notice box."""
    cell = Paragraph(text, Styles.body_small)
    t = Table([[cell]], colWidths=[CONTENT_W])
    t.setStyle(TableStyle([
        ("BACKGROUND",    (0, 0), (-1, -1), WARN_BG),
        ("BOX",           (0, 0), (-1, -1), 1.0, WARN_BORDER),
        ("LEFTPADDING",   (0, 0), (-1, -1), 8),
        ("RIGHTPADDING",  (0, 0), (-1, -1), 8),
        ("TOPPADDING",    (0, 0), (-1, -1), 6),
        ("BOTTOMPADDING", (0, 0), (-1, -1), 6),
    ]))
    return t


def _chart_block(drawing: Drawing, caption: str) -> list:
    return [
        Spacer(1, 3 * mm),
        DrawingFlowable(drawing),
        Paragraph(caption, Styles.caption),
        Spacer(1, 2 * mm),
    ]


# ── Section builders ─────────────────────────────────────────────────────────

def _build_cover(
    story: list,
    report: dict[str, Any],
    analysis: dict[str, Any],
) -> None:
    period_start = analysis["reporting_period"]["start_date"]["value"]
    period_end   = analysis["reporting_period"]["end_date"]["value"]
    generated    = report.get("generation_timestamp", "")[:10]
    model_name   = report.get("model_name", "GenAR")

    cover_d = _build_cover_drawing(
        product="Bisoprolol",
        period_start=period_start,
        period_end=period_end,
        generated_date=generated,
        model_name=model_name,
    )
    story.append(DrawingFlowable(cover_d))
    story.append(PageBreak())


def _get_section(report: dict[str, Any], name: str) -> dict[str, Any]:
    for s in report.get("sections", []):
        if s["section_name"] == name:
            return s
    return {}


def _section_text(section: dict[str, Any]) -> str:
    content = section.get("generated_content", "")
    if isinstance(content, list):
        return f"[Structured listing — {len(content)} rows. See Case Index / Listing section.]"
    return str(content)


def _build_toc(story: list, sections: list[str]) -> None:
    story += _section_heading("", "Table of Contents")
    toc_data = [
        [Paragraph("<b>Section</b>", Styles.table_cell_bold),
         Paragraph("<b>Title</b>",   Styles.table_cell_bold)]
    ]
    for i, name in enumerate(sections, 1):
        toc_data.append([
            Paragraph(str(i), Styles.table_cell_center),
            Paragraph(name,   Styles.table_cell),
        ])
    toc_data.append([
        Paragraph("App.", Styles.table_cell_center),
        Paragraph("Evidence / Traceability Appendix", Styles.table_cell),
    ])
    t = Table(toc_data, colWidths=[20 * mm, CONTENT_W - 20 * mm])
    t.setStyle(standard_table_style())
    story.append(t)
    story.append(PageBreak())


def _build_reporting_period(story: list, report: dict, analysis: dict) -> None:
    section = _get_section(report, "Reporting Period")
    story += _section_heading("1", "Reporting Period")
    story.append(Paragraph(_section_text(section), Styles.body))
    period = analysis["reporting_period"]
    data = [
        [Paragraph("<b>Attribute</b>", Styles.table_header),
         Paragraph("<b>Value</b>", Styles.table_header),
         Paragraph("<b>Source Fields</b>", Styles.table_header)],
        [Paragraph("Period Start", Styles.table_cell_bold),
         Paragraph(period["start_date"]["value"], Styles.table_cell),
         Paragraph(", ".join(period["start_date"].get("source_fields", [])), Styles.body_small)],
        [Paragraph("Period End", Styles.table_cell_bold),
         Paragraph(period["end_date"]["value"], Styles.table_cell),
         Paragraph(", ".join(period["end_date"].get("source_fields", [])), Styles.body_small)],
    ]
    t = Table(data, colWidths=[50 * mm, 45 * mm, 90 * mm])
    t.setStyle(standard_table_style())
    story.append(t)
    story.append(Spacer(1, 3 * mm))
    story.append(_ev_tag(section.get("evidence_ids", [])))
    story.append(PageBreak())


