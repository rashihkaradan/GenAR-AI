# ── Main generator ────────────────────────────────────────────────────────────

def generate_pdf(
    report_path: str | Path = "output/pader_report.json",
    analysis_path: str | Path = "data/analysis_results.json",
    evidence_path: str | Path = "data/evidence.json",
    output_path: str | Path = "output/Bisoprolol_PADER_Report.pdf",
) -> Path:
    """Generate the PADER PDF and return the output path."""
    report_path   = Path(report_path)
    analysis_path = Path(analysis_path)
    evidence_path = Path(evidence_path)
    output_path   = Path(output_path)

    report   = json.loads(report_path.read_text(encoding="utf-8"))
    analysis = json.loads(analysis_path.read_text(encoding="utf-8"))
    evidence = json.loads(evidence_path.read_text(encoding="utf-8"))

    output_path.parent.mkdir(parents=True, exist_ok=True)

    period_start = analysis["reporting_period"]["start_date"]["value"]
    period_end   = analysis["reporting_period"]["end_date"]["value"]
    report_period = f"{period_start} – {period_end}"

    # ── Doc template ────────────────────────────────────────────────
    on_page = _make_header_footer("Bisoprolol", report_period)

    # Cover frame — full bleed (no margins)
    cover_frame = Frame(0, 0, PAGE_W, PAGE_H, leftPadding=0, rightPadding=0,
                        topPadding=0, bottomPadding=0, id="cover")
    # Content frame — with margins
    content_frame = Frame(
        MARGIN_LEFT, MARGIN_BOTTOM,
        CONTENT_W, PAGE_H - MARGIN_TOP - MARGIN_BOTTOM,
        leftPadding=0, rightPadding=0, topPadding=0, bottomPadding=0,
        id="content",
    )

    doc = BaseDocTemplate(
        str(output_path),
        pagesize=A4,
        leftMargin=0, rightMargin=0,
        topMargin=0, bottomMargin=0,
    )
    cover_template  = PageTemplate(id="Cover",   frames=[cover_frame],
                                   onPage=on_page)
    content_template = PageTemplate(id="Content", frames=[content_frame],
                                    onPage=on_page)
    doc.addPageTemplates([cover_template, content_template])

    # ── Story ────────────────────────────────────────────────────────
    story: list = []

    # 0. Cover
    _build_cover(story, report, analysis)
    story.append(NextPageTemplate("Content"))

    # 1. TOC
    section_names = [
        "Reporting Period",
        "Narrative Summary and Analysis",
        "Summary Analysis of Cases",
        "Reaction / Adverse Event Analysis",
        "Serious Cases / 15-Day Alerts",
        "Trends and Important Observations",
        "History of Actions",
        "Case Index / Listing",
        "Data Limitations",
    ]
    _build_toc(story, section_names)

    # 2. Sections
    _build_reporting_period(story, report, analysis)
    _build_narrative(story, report, analysis)
    _build_case_summary(story, report, analysis)
    _build_reaction_analysis(story, report, analysis)
    _build_serious_alerts(story, report, analysis)
    _build_trends(story, report, analysis)
    _build_history_of_actions(story, report)
    _build_case_index(story, report)
    _build_data_limitations(story, report, analysis)

    # 3. Evidence appendix
    _build_evidence_appendix(story, evidence)

    doc.build(story)
    return output_path


